//! The US base layout the virtual keyboard always carries, at real evdev
//! keycodes so that applications reading hardware codes see a physical
//! keyboard.

/// One base key: the evdev keycode, its plain keysym and, when it has one,
/// the keysym on the Shift level.
pub(super) struct BaseKey {
    pub(super) evdev: u32,
    pub(super) plain: u32,
    pub(super) shifted: Option<u32>,
}

const fn one(evdev: u32, plain: u32) -> BaseKey {
    BaseKey {
        evdev,
        plain,
        shifted: None,
    }
}

const fn two(evdev: u32, plain: u8, shifted: u8) -> BaseKey {
    BaseKey {
        evdev,
        plain: plain as u32,
        shifted: Some(shifted as u32),
    }
}

